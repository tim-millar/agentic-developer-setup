  def test_multiple_python_roots_and_same_scope_mixed_ecosystem
    uv_project(prefix: "apps/one/")
    write_target("apps/two/setup.cfg", "[metadata]\nname = other\n")
    broad = assess(python_selection)
    assert_equal "blocked", broad.dig("composition", "status")
    assert_includes codes(broad), "scope_conflict"
    paths = broad["candidates"].select { |item| item["id"] == "python" && item["status"] == "detected" }.map { |item| item.dig("scope", "path") }
    assert_equal %w[apps/one apps/two], paths
    scope = {"type" => "workspace", "path" => "apps/one"}
    narrowed = assess(python_selection(scope: scope))
    assert_equal "ready", narrowed.dig("composition", "status")
    assert_equal %w[apps/one apps/one], python_commands(narrowed).first.values_at("scope", "cwd")
    assert narrowed["evidence"].all? { |item| !item["path"] || item["path"].start_with?("apps/one/") }
    write_target("apps/one/package.json", '{"name":"synthetic-mixed"}')
    assert_includes codes(assess(python_selection(scope: scope))), "repository_evidence_conflict"
    assert_includes codes(assess(selected(["ecosystem", "node"], scope: scope))), "repository_evidence_conflict"
  end

