  def test_uv_packaging_preserves_native_argv_and_deterministic_provenance
    uv_project
    write_target("src/sample/__init__.py", "# Public fixture\n")
    write_target("tests/test_example.py", "# Directory evidence only\n")
    unselected = assess
    candidate = unselected["candidates"].find { |item| item["id"] == "python" }
    assert_equal %w[detected high], candidate.values_at("status", "confidence")
    refute_empty candidate["evidence"]
    assert_empty unselected["selected"]
    assert_empty invocations(unselected)
    refute unselected["evidence"].any? { |item| item["path"].to_s.end_with?(".py") }
    result = assess(python_selection)
    assert_equal result, assess(python_selection)
    assert_equal [%w[make test]], invocations(result)
    command = python_commands(result).first
    assert_equal [".", ".", {}, ["standard"]], command.values_at("scope", "cwd", "env", "profiles")
    assert command["provenance"].any? { |item| item["adapter_id"] == "python" && item["adapter_version"] == "1.0.0" }
    assert_findings result, "distribution", "src-layout", "manager-version-uv"
  end

